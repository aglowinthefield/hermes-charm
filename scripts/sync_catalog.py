"""Generate the README catalog and native settings schema from customizations.json."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
START = '<!-- charm:catalog:start -->'
END = '<!-- charm:catalog:end -->'
LABELS = {
    'homebrew': 'Homebrew policy, no planned upstream submission',
    'upstream': 'Temporary fixes awaiting upstream merges',
    'mixed': 'Mixed upstream fixes and homebrew policy',
    'retirement-review': 'Upstream successor merged, retirement needs verification',
}


def render(data):
    rows = data['customizations']
    ids = [row['id'] for row in rows]
    active = [line.strip() for line in (ROOT / 'local-patches/ACTIVE').read_text().splitlines()
              if line.strip() and not line.lstrip().startswith('#')]
    if ids != active or len(ids) != len(set(ids)):
        raise ValueError('Catalog must cover ACTIVE exactly and in application order')
    manifest = ['# Generated by scripts/sync_catalog.py from customizations.json.',
                'name: charm', 'version: "0.2.0"',
                'description: Maintained Hermes customizations with explicit per-profile controls',
                'provides_tools: []', 'capabilities: []', 'config_schema:']
    docs = [START, '## Customizations', '',
            f"Upstream status checked at `{data['upstream_checked_at']}`. This is a snapshot, not a live query.", '',
            'Each row is one independent toggle. All ship enabled by default to preserve the existing active set.',
            'A merge is a reason to review retirement, not permission to silently remove a patch.', '']
    for row in rows:
        if not re.fullmatch(r'[a-z0-9][a-z0-9_-]*', row['id']):
            raise ValueError('Invalid customization identifier')
        if type(row['default_enabled']) is not bool or not row['summary']:
            raise ValueError('Every customization needs a boolean default and a summary')
        if row['maintenance'] not in LABELS:
            raise ValueError('Unrecognized maintenance classification')
        description = row['title'] + '. ' + row['summary'] + ' Requires explicit apply and backend restart.'
        manifest.extend([f"  {row['id']}:", '    type: bool',
                         '    default: ' + json.dumps(row['default_enabled']),
                         '    description: ' + json.dumps(description)])
    for kind, heading in LABELS.items():
        docs.extend(['### ' + heading, '', '| Toggle | What it changes | Upstream / maintenance |',
                     '| --- | --- | --- |'])
        for row in rows:
            if row['maintenance'] != kind:
                continue
            sources = '; '.join(source['reference'] + ' (' +
                                ('closed without merge' if source['state'] == 'closed' else source['state']) + ')'
                                for source in row['sources'])
            maintenance = (sources + '. ' if sources else '') + row['note']
            docs.append(f"| `{row['id']}` | {row['summary']} | {maintenance} |")
        docs.append('')
    docs.extend(['The token-hygiene row is one atomic group of overlapping handoff/prompt changes.',
                 'Its upstream portions and local policy cannot be switched separately yet.',
                 'Skill-pin tolerance has its own toggle; it is no longer duplicated inside token hygiene.', '', END])
    return '\n'.join(manifest) + '\n', '\n'.join(docs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        manifest, section = render(json.loads((ROOT / 'customizations.json').read_text()))
        readme = (ROOT / 'README.md').read_text()
        if readme.count(START) != 1 or readme.count(END) != 1:
            raise ValueError('README requires one catalog marker pair')
        before, rest = readme.split(START)
        _, after = rest.split(END)
        expected = {'plugin.yaml': manifest, 'README.md': before + section + after}
        changed = [name for name, content in expected.items() if (ROOT / name).read_text() != content]
        if args.check:
            if changed:
                raise ValueError('Catalog views stale: ' + ', '.join(changed))
        else:
            for name in changed:
                (ROOT / name).write_text(expected[name])
        print('Catalog, native settings schema and README are synchronized.')
        return 0
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f'catalog: {exc}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
